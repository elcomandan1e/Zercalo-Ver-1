  function _esc(s){
    return String(s == null ? '' : s).replace(/[&<>"']/g, function(c){
      return ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'})[c];
    });
  }

  function _renderDocsModal(){
    var keys = Object.keys(DOCS);
    if(!window._zrzDocsV2Tab || keys.indexOf(window._zrzDocsV2Tab) < 0){
      window._zrzDocsV2Tab = keys[0];
    }
    var cur = window._zrzDocsV2Tab;
    var d = DOCS[cur];
    if(!d) return;

    var html = '<h2>' + (typeof LOGO_MARK === 'function' ? LOGO_MARK(30) : '') + ' Документация</h2>';

    html += '<div style="display:flex;flex-wrap:wrap;gap:6px;margin:8px 0 12px">';
    keys.forEach(function(k){
      var isAct = (k === cur);
      html += '<button type="button" class="chip ' + (isAct ? 'active' : '') + '" onclick="zrzDocsV2Open(\'' + k + '\')">' + _esc(DOCS[k].title) + '</button>';
    });
    html += '</div>';

    html += '<div style="max-height:56vh;overflow-y:auto;padding:12px 14px;background:var(--line-soft);border-radius:12px;border:1px solid var(--line);font-size:13px;line-height:1.6;white-space:pre-wrap;word-break:break-word;font-family:ui-monospace,Menlo,Consolas,monospace;color:var(--text)">'
      + _esc(d.content) + '</div>';

    html += '<button class="btn btn-secondary" onclick="zrzDocsV2Copy()">📋 Скопировать</button>';
    html += '<button class="btn btn-secondary" onclick="zrzDocsV2Download()">💾 Скачать .md</button>';
    html += '<button class="btn btn-secondary" onclick="closeModal()">Закрыть</button>';

    if(typeof showModal === 'function') showModal(html);
  }

  window.zrzDocsV2Open = function(key){
    if(DOCS[key]) window._zrzDocsV2Tab = key;
    _renderDocsModal();
  };

  window.zrzDocsV2Copy = function(){
    var d = DOCS[window._zrzDocsV2Tab];
    if(!d) return;
    var txt = d.content;
    if(navigator.clipboard && navigator.clipboard.writeText){
      navigator.clipboard.writeText(txt).then(function(){
        if(typeof uiAlert === 'function') uiAlert('✔ Скопировано');
      });
    } else {
      if(typeof uiAlert === 'function') uiAlert(txt);
    }
  };

  window.zrzDocsV2Download = function(){
    var d = DOCS[window._zrzDocsV2Tab];
    if(!d) return;
    var blob = new Blob([d.content], {type: 'text/markdown;charset=utf-8'});
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = (window._zrzDocsV2Tab || 'doc') + '.md';
    document.body.appendChild(a);
    a.click();
    setTimeout(function(){ a.remove(); }, 100);
    setTimeout(function(){ try{ URL.revokeObjectURL(url); }catch(e){} }, 1000);
  };

