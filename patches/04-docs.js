  function installDocs(){
    try {
      if(!window.ZRZ_DOCS) window.ZRZ_DOCS = {};
      var merged = window.ZRZ_DOCS;
      /* Наш bag имеет приоритет — перезаписываем старые вкладки. */
      for(var k in bag){
        if(!Object.prototype.hasOwnProperty.call(bag, k)) continue;
        merged[k] = bag[k];
      }
      /* Если активная вкладка из старой версии уже не существует — сброс. */
      if(window._docsTab && !merged[window._docsTab]) window._docsTab = 'README';
    } catch(e){}
  }

  function wrapOpenDocs(){
    if(window._zrz04DocsWrapWrapped) return;
    if(typeof window.openDocs !== 'function') return;
    var orig = window.openDocs;
    window.openDocs = function(){
      installDocs();
      return orig.apply(this, arguments);
    };
    window._zrz04DocsWrapWrapped = true;
  }

  function apply(){
    try{ installDocs(); }catch(e){}
    try{ wrapOpenDocs(); }catch(e){}
  }

  if(document.body) apply();
  else document.addEventListener('DOMContentLoaded', apply, {once:true});
  setTimeout(apply, 600);
  setTimeout(apply, 1800);

